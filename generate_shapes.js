function circlePoints(cx, cy, r, num) {
  let pts = [];
  for(let i=0; i<num; i++) {
    pts.push([
      Number((cx + Math.cos(i/num * Math.PI * 2) * r).toFixed(3)),
      Number((cy + Math.sin(i/num * Math.PI * 2) * r).toFixed(3))
    ]);
  }
  return pts;
}

